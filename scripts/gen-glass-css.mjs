#!/usr/bin/env node
/**
 * Generate src/client/glass/glass-css.gen.ts — the glass stylesheet text as
 * an embeddable string, so the browser half can lazy-load the glass CSS
 * (item II: the style tag is only mounted while the glass layer is enabled).
 *
 * Why this exists: the tsdown client preset auto-injects every imported
 * `*.module.css` as a <style> tag at bundle evaluation time, i.e. at plugin
 * load regardless of glass usage. Keeping the text in a plain TS module
 * skips that path entirely: `glass-layer.ts` owns the <style> tag and
 * appends/removes it on enable/disable.
 *
 * The physical `glass.module.css` stays the single source of truth — this
 * script is a build step, not a second copy to maintain by hand. Rebuild
 * whenever that file changes (pnpm build / pnpm watch both run this first).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const SOURCE = join(__dirname, '..', 'src', 'client', 'glass', 'glass.module.css')
const OUT = join(__dirname, '..', 'src', 'client', 'glass', 'glass-css.gen.ts')

const sourceBuffer = readFileSync(SOURCE)

// lightningcss is a devDependency (always present in this repo's build).
// When it is missing (e.g. a bare node_modules checkout running `prepare`),
// fall back to the raw stylesheet text — only the byte size differs.
let cssText = sourceBuffer.toString('utf8')
try {
  const { transform } = await import('lightningcss')
  const { code } = transform({ filename: SOURCE, code: sourceBuffer, minify: true })
  cssText = code.toString()
} catch (error) {
  // Loud on purpose (audit F9): the fallback ships the stylesheet UNMINIFIED and
  // unprocessed, so the emitted artifact silently differs from every other
  // build. Today that only costs bytes, but any future transform here would
  // degrade invisibly.
  console.warn(`[gen-glass-css] lightningcss unavailable — shipping the raw stylesheet: ${String(error)}`)
}

const lines = [
  `/**`,
  ` * AUTO-GENERATED by scripts/gen-glass-css.mjs — do not edit by hand.`,
  ` * The glass stylesheet text, generated from`,
  ` * src/client/glass/glass.module.css on every build. The browser half`,
  ` * mounts this text as a <style> tag only while the glass layer is on`,
  ` * (item II — lazy CSS), so editing the stylesheet means editing`,
  ` * glass.module.css and rebuilding.`,
  ` */`,
  `export const GLASS_CSS_TEXT: string = ${JSON.stringify(cssText)}`,
  ``,
]
writeFileSync(OUT, lines.join('\n'))
console.log(`wrote ${OUT} (${cssText.length} bytes)`)